import assert from 'node:assert/strict';

export async function auditStickers(request, db, proof, token) {
  const data = {title:'Sticker audit',slug:'sticker-audit',prizes:['Premio local'],prizeSources:[0],priceCrc:2000,numbersPerSticker:2,numberCount:1000,packages:[{quantity:2,priceCrc:2000},{quantity:30,priceCrc:25000}]};
  for (const packages of [[{quantity:3,priceCrc:2000}], [{quantity:2,priceCrc:2000},{quantity:2,priceCrc:3000}], [{quantity:102,priceCrc:2000}], [{quantity:2,priceCrc:0}]]) assert.equal((await request('/api/admin/campaigns',{...data,packages},'',token)).status,400);
  const created = await request('/api/admin/campaigns', data, '', token);
  assert.equal(created.status,201);
  const id=created.data.id;
  assert.equal(created.data.numbersPerSticker,2);
  for(let i=0;i<3;i++) assert.equal((await request(`/api/admin/campaigns/${id}/photos`,proof,'',token)).status,201);
  assert.equal((await request(`/api/admin/campaigns/${id}/photos`,proof,'',token)).status,409);
  assert.equal((await request(`/api/admin/campaigns/${id}/publish`,{},'',token)).status,200);
  assert.equal((await request('/api/campaigns/sticker-audit/proposal',{quantity:3})).status,400);
  assert.equal((await request('/api/campaigns/sticker-audit/proposal',{quantity:4})).status,400);
  const publicRaffle=await request('/api/campaigns/sticker-audit');
  assert.deepEqual(publicRaffle.data.packages,[{quantity:2,priceCrc:2000},{quantity:30,priceCrc:25000}]);
  const proposal=await request('/api/campaigns/sticker-audit/proposal',{quantity:30});
  assert.equal(proposal.status,200);assert.equal(proposal.data.values.length,30);
  const competing=await request('/api/campaigns/sticker-audit/proposal',{quantity:2,values:proposal.data.values.slice(0,2)});
  assert.equal(competing.status,409);
  assert.equal((await request('/api/admin/reservations',{})).status,401);
  assert.equal((await request('/api/admin/reservations',{},'','forged')).status,401);
  const order=await request('/api/admin/reservations',{campaignId:id,values:proposal.data.values,buyerName:'Sticker audit',buyerEmail:'audit@example.invalid',buyerPhone:'00000000',totalCrc:1,stickerCount:1},proposal.cookie,token);
  assert.equal(order.status,201);assert.equal(order.data.totalCrc,25000);
  const lookup=await request('/api/reservations/lookup',{token:order.data.token});
  assert.equal(lookup.data.stickerCount,15);assert.equal(lookup.data.numbersPerSticker,2);
  assert.ok(order.data.reservationId);
  assert.equal((await request(`/api/reservations/${order.data.token}/proofs`,proof)).status,201);
  assert.equal((await request('/api/reservations/lookup',{token:order.data.token})).data.status,'PENDING_REVIEW');
  const stored=await db.reservation.findUnique({where:{lookupToken:order.data.token}});
  const email=await db.emailNotification.findFirst({where:{reservationId:stored.id,kind:'RESERVED'}});
  assert.match(email.html,/15 stickers/);
  const patch = async body => {const response=await fetch('http://127.0.0.1:4199/api/admin/campaigns/'+id,{method:'PATCH',headers:{'Content-Type':'application/json',Authorization:'Bearer '+token},body:JSON.stringify({title:data.title,description:'',...body})});return {status:response.status,data:await response.json()};};
  assert.equal((await patch({drawMode:'DATE',drawDate:null})).status,400);
  const dated=await patch({drawMode:'DATE',drawDate:'2020-01-01T00:00:00.000Z'});
  assert.equal(dated.status,200);assert.equal(dated.data.drawMode,'DATE');
  assert.equal((await patch({})).data.drawDate,'2020-01-01T00:00:00.000Z');
  // Expired countdown must not close sales or change existing orders.
  const pending=await request('/api/campaigns/sticker-audit/proposal',{quantity:30});
  assert.equal(pending.status,200);
  for(const drawMode of ['SOLD_OUT','ANNOUNCED']) {
    const changed=await patch({drawMode});assert.equal(changed.status,200);assert.equal(changed.data.drawDate,null);
    assert.equal((await request('/api/reservations/lookup',{token:order.data.token})).data.totalCrc,25000);
  }
  console.log('Draw schedule PASS: date required, live edits preserved orders, elapsed date permits sales, optional modes clear date');
  assert.equal((await patch({packages:[{quantity:3,priceCrc:100}]})).status,400);
  assert.equal((await patch({numbersPerSticker:3})).status,400);
  assert.equal((await patch({packages:[{quantity:2,priceCrc:1500},{quantity:30,priceCrc:22000}]})).status,200);
  assert.equal((await request('/api/reservations/lookup',{token:order.data.token})).data.totalCrc,25000);
  assert.deepEqual((await db.reservation.findUnique({where:{id:stored.id}})).selectedValues,stored.selectedValues);
  const body={campaignId:id,values:pending.data.values,buyerName:'New buyer',buyerEmail:'audit@example.invalid',buyerPhone:'00000000'};
  assert.equal((await request('/api/reservations',{...body,expectedTotalCrc:25000},pending.cookie)).status,409);
  const updatedOrder=await request('/api/reservations',{...body,expectedTotalCrc:22000},pending.cookie);
  assert.equal(updatedOrder.status,201);assert.equal(updatedOrder.data.totalCrc,22000);
  await db.reservation.update({where:{id:stored.id},data:{status:'CONFIRMED'}});
  assert.equal((await patch({packages:[{quantity:2,priceCrc:1800}]})).status,200);
  const original=await request('/api/reservations/lookup',{token:order.data.token});
  assert.equal(original.data.totalCrc,25000);assert.equal(original.data.stickerCount,15);
  assert.equal((await request('/api/campaigns/sticker-audit/proposal',{quantity:30})).status,400);
  const cashProposal=await request('/api/campaigns/sticker-audit/proposal',{quantity:2});
  const cashBody={campaignId:id,values:cashProposal.data.values,buyerName:'Cash audit',buyerEmail:'audit@example.invalid',buyerPhone:'88888888',paymentMethod:'CASH',cashReceived:true,expectedTotalCrc:1800};
  assert.equal((await request('/api/reservations',cashBody,cashProposal.cookie)).status,403);
  assert.equal((await request('/api/reservations',cashBody,cashProposal.cookie,token)).status,403);
  assert.equal((await request('/api/admin/reservations',{...cashBody,cashReceived:false},cashProposal.cookie,token)).status,400);
  const cashOrder=await request('/api/admin/reservations',cashBody,cashProposal.cookie,token);
  assert.equal(cashOrder.status,201);
  const cashStored=await db.reservation.findUnique({where:{id:cashOrder.data.reservationId},include:{numbers:true,proofs:true,emails:true}});
  assert.equal((await request('/api/admin/reservations/'+cashOrder.data.reservationId,undefined,'',token)).data.paymentMethod,'CASH');
  assert.equal(cashStored.paymentMethod,'CASH');assert.equal(cashStored.status,'CONFIRMED');assert.ok(cashStored.confirmedAt);
  assert.equal(cashStored.proofs.length,0);assert.equal(cashStored.numbers.length,2);assert.ok(cashStored.numbers.every(n=>n.status==='SOLD'));
  assert.deepEqual(cashStored.emails.map(e=>e.kind),['CONFIRMED']);assert.match(cashStored.emails[0].html,/efectivo recibido/);
  assert.equal((await request('/api/reservations/lookup',{token:cashOrder.data.token})).data.paymentMethod,'CASH');
  assert.equal((await request('/api/admin/reservations',cashBody,cashProposal.cookie,token)).status,409);
  assert.equal((await request('/api/campaigns/sticker-audit/proposal',{quantity:2,values:cashBody.values})).status,409);
  console.log('Cash PASS: admin-only, receipt acknowledgment required, atomic SOLD without proof, one confirmation email, replay and duplicate numbers rejected');
  console.log('Live cards PASS: pending and confirmed snapshots preserved; stale total rejected; new price used; removed quantities blocked; rules immutable');
  console.log(JSON.stringify({stickers:'PASS',checks:['15 stickers / 30 unique numbers / CRC 25000','price and count tampering ignored','incomplete sticker rejected','held numbers excluded','three-photo limit','order snapshot and email']}));
}
